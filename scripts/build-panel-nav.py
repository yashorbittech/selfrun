#!/usr/bin/env python3
"""Regenerates src/lib/ai/agent/guide/nav.generated.ts: every screen of every panel (from app/<panel>/**/page.tsx), so the AI agent can
tell people exactly where things are. Run from src/:  python3 ../scripts/build-panel-nav.py"""
import os, re, json

PANELS = ["pms", "hrms", "fms", "lms", "tms", "prms", "smms", "sop", "dlms", "seo", "ots", "lpms", "aibots", "messenger", "intelligence", "cms", "portal", "support", "workspace", "platform"]

def title_of(path):
    s = open(path, errors="ignore").read()
    m = re.search(r'metadata[^=]*=\s*\{\s*title:\s*"([^"]+)"', s)
    return m.group(1) if m else None

def human(href):
    segs = href.strip("/").split("/")[1:]
    if not segs:
        return "Dashboard"
    return " › ".join("details" if s.startswith("[") else s.replace("-", " ").title() for s in segs)

out = {}
for p in PANELS:
    base = os.path.join("app", "(platform)", "platform") if p == "platform" else os.path.join("app", p)
    if not os.path.isdir(base):
        continue
    rows = []
    for root, _dirs, files in os.walk(base):
        if "page.tsx" not in files:
            continue
        segs = [s for s in os.path.relpath(root, "app").split("/") if not (s.startswith("(") and s.endswith(")"))]
        if any(x in segs for x in ("login", "change-password", "[...notFound]")):
            continue
        if sum(1 for s in segs if s.startswith("[")) > 1:
            continue
        href = "/" + "/".join(segs)
        rows.append((href, title_of(os.path.join(root, "page.tsx"))))
    out[p] = sorted(rows)

lines = ["// GENERATED by scripts/build-panel-nav.py from app/<panel>/**/page.tsx — do not edit by hand.", "// Every screen of every panel, so the AI agent can say exactly where something is.", "export const PANEL_ROUTES: Record<string, { path: string; name: string }[]> = {"]
for p, rows in out.items():
    lines.append(f"  {p}: [")
    for href, t in rows:
        lines.append(f"    {{ path: {json.dumps(re.sub(r'\\[(\\w+)\\]', r':\\1', href))}, name: {json.dumps(t or human(href))} }},")
    lines.append("  ],")
lines.append("};")
open("lib/ai/agent/guide/nav.generated.ts", "w").write("\n".join(lines) + "\n")
