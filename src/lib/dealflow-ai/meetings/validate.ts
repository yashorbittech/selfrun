import { normalizeE164 } from "@/lib/products/agentos/calls/phone";
import { DEFAULT_AGENT_RUNTIME, MEETING_LIMITS, type AgentRuntimeSettings, type MeetingAgenda, type MeetingParticipant, type MeetingRole, type MeetingTarget, type ParticipantKind } from "@/lib/dealflow-ai/meetings/types";

/** Input checking for scheduling and roster changes. Pure: no database, no clock except what is passed in. */

export const EMAIL_RE = /^[^\s@]{1,64}@[^\s@.]+(\.[^\s@.]+)+$/;
export const MIN_DURATION = 5;
export const MAX_DURATION = 480;
const MAX_AHEAD_MS = 2 * 365 * 24 * 3600 * 1000;
const PAST_GRACE_MS = 5 * 60_000;

export type Parsed<T> = { ok: true; value: T } | { ok: false; error: string };
const fail = (error: string): { ok: false; error: string } => ({ ok: false, error });

/** Visible text: control characters out, whitespace collapsed, length capped. */
export function cleanText(v: unknown, max: number): string {
  return typeof v === "string" ? v.replace(/[\u0000-\u001f\u007f]+/g, " ").replace(/\s+/g, " ").trim().slice(0, max) : "";
}
function cleanMultiline(v: unknown, max: number): string {
  return typeof v === "string" ? v.replace(/\r\n?/g, "\n").replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, "").trim().slice(0, max) : "";
}

export function isValidTimezone(tz: unknown): tz is string {
  if (typeof tz !== "string" || !tz || tz.length > 64) return false;
  try {
    new Intl.DateTimeFormat("en-US", { timeZone: tz });
    return true;
  } catch {
    return false;
  }
}

export function parseEmail(v: unknown): string | "" | null {
  const s = typeof v === "string" ? v.trim().toLowerCase() : "";
  if (!s) return "";
  return s.length <= 200 && EMAIL_RE.test(s) ? s : null;
}

export interface ParticipantInput {
  kind: ParticipantKind;
  role?: MeetingRole;
  name?: string;
  refId?: string | null;
  email?: string;
  phone?: string;
  company?: string;
  aliases?: string[];
}

/** Server-resolved facts about a referenced staff member / agent: the name and email the browser claims are never trusted for those. */
export interface Directory {
  staff: Map<string, { name: string; email: string }>;
  agents: Map<string, { name: string }>;
}

export function parseAliases(raw: unknown, ownName: string): Parsed<string[]> {
  if (raw === undefined || raw === null) return { ok: true, value: [] };
  if (!Array.isArray(raw)) return fail("Aliases must be a list of names.");
  const seen = new Set([ownName.toLowerCase()]);
  const out: string[] = [];
  for (const a of raw) {
    const t = cleanText(a, 40);
    if (!t) continue;
    if (seen.has(t.toLowerCase())) continue;
    seen.add(t.toLowerCase());
    out.push(t);
  }
  if (out.length > 8) return fail("An agent can have at most 8 aliases.");
  return { ok: true, value: out };
}

/** One participant, normalised. `id` is kept for existing people and generated by the caller for new ones. */
export function normalizeParticipant(raw: unknown, dir: Directory, id: () => string, now: Date): Parsed<MeetingParticipant> {
  if (typeof raw !== "object" || raw === null || Array.isArray(raw)) return fail("Each participant must be an object.");
  const r = raw as ParticipantInput;
  if (r.kind !== "internal" && r.kind !== "external" && r.kind !== "agent") return fail("A participant must be staff, a guest or an AI agent.");
  const stamp = now.toISOString();
  if (r.kind === "internal") {
    const refId = typeof r.refId === "string" ? r.refId : "";
    const u = dir.staff.get(refId);
    if (!u) return fail("One of the selected staff members is not part of this company.");
    const role: MeetingRole = r.role === "host" || r.role === "cohost" ? r.role : "participant";
    return { ok: true, value: { id: id(), kind: "internal", role, name: u.name, refId, email: u.email || undefined, invitedAt: stamp } };
  }
  if (r.kind === "agent") {
    const refId = typeof r.refId === "string" ? r.refId : "";
    const a = dir.agents.get(refId);
    if (!a) return fail("One of the selected agents is no longer available. Refresh and pick again.");
    const aliases = parseAliases(r.aliases, a.name);
    if (!aliases.ok) return aliases;
    return { ok: true, value: { id: id(), kind: "agent", role: "participant", name: a.name, refId, aliases: aliases.value, invitedAt: stamp } };
  }
  const name = cleanText(r.name, MEETING_LIMITS.nameMax);
  if (name.length < 1) return fail("Every guest needs a name.");
  const email = parseEmail(r.email);
  if (email === null) return fail(`"${cleanText(r.email, 60)}" is not a valid email address.`);
  let phone: string | undefined;
  if (typeof r.phone === "string" && r.phone.trim()) {
    const p = normalizeE164(r.phone);
    if (!p) return fail(`The phone number for ${name} must be in international format, for example +919876543210.`);
    phone = p;
  }
  const company = cleanText(r.company, 160);
  return { ok: true, value: { id: id(), kind: "external", role: "participant", name, refId: null, ...(email ? { email } : {}), ...(phone ? { phone } : {}), ...(company ? { company } : {}), joinTokenHash: null, invitedAt: stamp } };
}

/** Checks the roster as a whole (caps, duplicates, host). Returns an error text or null. */
export function checkRoster(list: MeetingParticipant[]): string | null {
  const humans = list.filter((p) => p.kind !== "agent");
  const agents = list.filter((p) => p.kind === "agent");
  if (humans.length > MEETING_LIMITS.humans) return `A meeting can have at most ${MEETING_LIMITS.humans} people.`;
  if (agents.length > MEETING_LIMITS.agents) return `A meeting can have at most ${MEETING_LIMITS.agents} AI agents.`;
  if (!list.some((p) => p.kind === "internal" && p.role === "host")) return "A meeting needs at least one host from your team.";
  const seen = new Map<string, string>();
  for (const p of list) {
    const keys: string[] = [];
    if (p.kind === "external") {
      if (p.email) keys.push(`e:${p.email}`);
      if (p.phone) keys.push(`t:${p.phone}`);
    } else if (p.refId) keys.push(`${p.kind}:${p.refId}`);
    for (const k of keys) {
      if (seen.has(k)) return `${p.name} is listed twice${seen.get(k) !== p.name ? ` (same ${k.startsWith("t:") ? "phone number" : k.startsWith("e:") ? "email" : "entry"} as ${seen.get(k)})` : ""}.`;
      seen.set(k, p.name);
    }
  }
  const names = new Set<string>();
  for (const a of agents) {
    // Two agents answering to the same name could not be told apart when someone addresses one of them.
    for (const n of [a.name, ...(a.aliases ?? [])].map((x) => x.toLowerCase())) {
      if (names.has(n)) return `Two agents answer to "${n}". Give one of them a different alias.`;
      names.add(n);
    }
  }
  return null;
}

export interface MeetingFields {
  title: string;
  agenda: MeetingAgenda | null;
  scheduledAt: string;
  durationMinutes: number;
  timezone: string;
  agentSettings: AgentRuntimeSettings;
  waitingRoom: boolean;
  target: MeetingTarget | null;
}

function parseAgenda(raw: unknown): Parsed<MeetingAgenda | null> {
  if (raw === undefined || raw === null) return { ok: true, value: null };
  if (typeof raw !== "object" || Array.isArray(raw)) return fail("The agenda is not valid.");
  const a = raw as Record<string, unknown>;
  const title = cleanText(a.title, 200);
  const description = cleanMultiline(a.description, 4000);
  const agentGoal = cleanMultiline(a.agentGoal, 2000);
  if (!title && !description && !agentGoal) return { ok: true, value: null };
  return { ok: true, value: { title: title || "Agenda", ...(description ? { description } : {}), ...(agentGoal ? { agentGoal } : {}) } };
}

export function parseAgentSettings(raw: unknown, base: AgentRuntimeSettings = DEFAULT_AGENT_RUNTIME): Parsed<AgentRuntimeSettings> {
  if (raw === undefined || raw === null) return { ok: true, value: { ...base } };
  if (typeof raw !== "object" || Array.isArray(raw)) return fail("The agent settings are not valid.");
  const r = raw as Record<string, unknown>;
  const num = (v: unknown, min: number, max: number, d: number) => (v === undefined ? d : typeof v === "number" && Number.isFinite(v) ? Math.min(max, Math.max(min, Math.round(v))) : NaN);
  const followUp = num(r.followUpWindowSecs, 0, 120, base.followUpWindowSecs);
  const maxAnswer = num(r.maxAnswerSecs, 5, 120, base.maxAnswerSecs);
  if (Number.isNaN(followUp) || Number.isNaN(maxAnswer)) return fail("The agent settings are not valid.");
  const bool = (v: unknown, d: boolean) => (typeof v === "boolean" ? v : d);
  return { ok: true, value: { respondOnlyWhenAddressed: true, followUpWindowSecs: followUp, allowBargeIn: bool(r.allowBargeIn, base.allowBargeIn), maxAnswerSecs: maxAnswer, useLeadBriefing: bool(r.useLeadBriefing, base.useLeadBriefing) } };
}

export function parseTarget(raw: unknown): Parsed<MeetingTarget | null> {
  if (raw === undefined || raw === null) return { ok: true, value: null };
  if (typeof raw !== "object" || Array.isArray(raw)) return fail("The linked record is not valid.");
  const t = raw as Record<string, unknown>;
  const entityType = cleanText(t.entityType, 40);
  const entityId = cleanText(t.entityId, 120);
  if (t.product !== "dealflow-ai" || !["lead", "applicant", "submission"].includes(entityType) || !entityId) return fail("The linked record is not valid.");
  return { ok: true, value: { product: "dealflow-ai", entityType, entityId, label: cleanText(t.label, 120) || "Contact" } };
}

/** The scheduling fields. With `base`, absent fields keep the existing value (an edit); without it they are required (a new meeting). */
export function parseMeetingFields(raw: Record<string, unknown>, now: Date, base?: MeetingFields): Parsed<MeetingFields> {
  const title = raw.title === undefined && base ? base.title : cleanText(raw.title, MEETING_LIMITS.titleMax);
  if (!title) return fail("Give the meeting a title.");
  let scheduledAt = base?.scheduledAt ?? "";
  if (raw.scheduledAt !== undefined || !base) {
    const d = new Date(typeof raw.scheduledAt === "string" ? raw.scheduledAt : "");
    if (Number.isNaN(d.getTime())) return fail("Pick a valid date and time.");
    const changed = !base || d.toISOString() !== base.scheduledAt;
    if (changed && d.getTime() < now.getTime() - PAST_GRACE_MS) return fail("The meeting time is in the past.");
    if (d.getTime() > now.getTime() + MAX_AHEAD_MS) return fail("The meeting time is too far ahead.");
    scheduledAt = d.toISOString();
  }
  let durationMinutes = base?.durationMinutes ?? 30;
  if (raw.durationMinutes !== undefined || !base) {
    const n = raw.durationMinutes === undefined ? 30 : Number(raw.durationMinutes);
    if (!Number.isFinite(n) || n < MIN_DURATION || n > MAX_DURATION) return fail(`Duration must be between ${MIN_DURATION} and ${MAX_DURATION} minutes.`);
    durationMinutes = Math.round(n);
  }
  let timezone = base?.timezone ?? "";
  if (raw.timezone !== undefined || !base) {
    if (!isValidTimezone(raw.timezone)) return fail("Pick a valid time zone.");
    timezone = raw.timezone;
  }
  const agenda = raw.agenda === undefined && base ? { ok: true as const, value: base.agenda } : parseAgenda(raw.agenda);
  if (!agenda.ok) return agenda;
  const settings = parseAgentSettings(raw.agentSettings, base?.agentSettings);
  if (!settings.ok) return settings;
  const target = raw.target === undefined && base ? { ok: true as const, value: base.target } : parseTarget(raw.target);
  if (!target.ok) return target;
  const waitingRoom = typeof raw.waitingRoom === "boolean" ? raw.waitingRoom : (base?.waitingRoom ?? false);
  return { ok: true, value: { title, agenda: agenda.value, scheduledAt, durationMinutes, timezone, agentSettings: settings.value, waitingRoom, target: target.value } };
}
