/**
 * Canonical JSON for hashing and golden files. Pure, client-safe. Object keys are sorted recursively; arrays keep their order; `undefined`
 * properties are omitted. Two equal documents always serialise to the same string, whatever order their keys were built in.
 */
export function canonicalJson(value: unknown): string {
  return JSON.stringify(sortKeys(value));
}

function sortKeys(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(sortKeys);
  if (v && typeof v === "object") {
    const o = v as Record<string, unknown>;
    const out: Record<string, unknown> = {};
    for (const k of Object.keys(o).sort()) if (o[k] !== undefined) out[k] = sortKeys(o[k]);
    return out;
  }
  return v;
}
